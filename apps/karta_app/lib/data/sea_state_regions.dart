  /// Resolves the highest-priority Southeast Asian state, federal territory,
  /// province, or district containing [coord]. Returns `null` if outside
  /// mapped Southeast Asian regions.
  static KartaStateRegion? resolve(Coordinate coord) {
    final candidates = allRegions.where((r) => r.contains(coord)).toList();
    if (candidates.isEmpty) return null;
    if (candidates.length == 1) return candidates.first;

    candidates.sort((a, b) {
      final pCmp = a.priority.compareTo(b.priority);
      if (pCmp != 0) return pCmp;
      final da = haversineMeters(coord, a.center);
      final db = haversineMeters(coord, b.center);
      return da.compareTo(db);
    });
    return candidates.first;
  }
