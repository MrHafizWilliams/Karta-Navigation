/// Administrative state, federal territory, province, or district boundary used
/// by Karta to greet travelers with the local flag when crossing borders across
/// all 11 Southeast Asian countries.
@immutable
class KartaStateRegion {
  const KartaStateRegion({
    required this.id,
    required this.name,
    required this.localName,
    required this.countryCode,
    required this.countryName,
    required this.flagId,
    required this.tagline,
    required this.minLat,
    required this.maxLat,
    required this.minLon,
    required this.maxLon,
    required this.center,
    this.priority = 10,
  });

  final String id;
  final String name;
  final String localName;
  final String countryCode;
  final String countryName;
  final String flagId;
  final String tagline;
  final double minLat;
  final double maxLat;
  final double minLon;
  final double maxLon;
  final Coordinate center;

  /// Lower numbers take precedence (e.g. Kuala Lumpur / Putrajaya before Selangor,
  /// Penang before Kedah/Perak, Singapore before Johor).
  final int priority;

  bool contains(Coordinate c) =>
      c.lat >= minLat && c.lat <= maxLat && c.lon >= minLon && c.lon <= maxLon;
}

