    nativeName: 'ภาษาไทย',
    englishName: 'Thai',
    regionHint: 'ประเทศไทย · Thailand',
  ),
  burmese(
    code: 'my',
    shortBadge: 'MY',
    nativeName: 'မြန်မာဘာသာ',
    englishName: 'Burmese',
    regionHint: 'မြန်မာ · Myanmar',
