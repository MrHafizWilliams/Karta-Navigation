/// InheritedWidget propagating the active [KartaStrings] localization throughout
/// both `karta_design_system` and `karta_app` widgets without circular deps.
class KartaL10nScope extends InheritedWidget {
  const KartaL10nScope({
    super.key,
    required this.language,
    required super.child,
  });

  final KartaLanguage language;

  KartaStrings get strings => KartaStrings.of(language);

  static KartaStrings of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<KartaL10nScope>();
    return scope?.strings ?? KartaStrings.of(KartaLanguage.english);
  }

  @override
  bool updateShouldNotify(KartaL10nScope oldWidget) =>
      oldWidget.language != language;
}

extension KartaL10nBuildContextX on BuildContext {
  KartaStrings get kartaStrings => KartaL10nScope.of(this);
}
