    englishName: 'Cambodian (Khmer)',
    regionHint: 'កម្ពុជា · Cambodia',
  ),
  lao(
    code: 'lo',
    shortBadge: 'LO',
    nativeName: 'ພາသາລາວ',
    englishName: 'Laotian (Lao)',
    regionHint: 'ລາວ · Laos',
  ),
  portuguese(
    code: 'pt',
    shortBadge: 'PT',
    nativeName: 'Português',
    englishName: 'Portuguese',
    regionHint: 'Timor-Leste',
  ),
  tagalog(
    code: 'tl',
    shortBadge: 'TL',
    nativeName: 'Tagalog',
    englishName: 'Tagalog (Filipino)',
    regionHint: 'Pilipinas · Philippines',
  );

  const KartaLanguage({
    required this.code,
    required this.shortBadge,
    required this.nativeName,
    required this.englishName,
    required this.regionHint,
  });

  final String code;
  final String shortBadge;
  final String nativeName;
  final String englishName;
  final String regionHint;

  static KartaLanguage fromCode(String? raw) {
    final normalized = (raw ?? 'en').trim().toLowerCase();
    for (final lang in KartaLanguage.values) {
      if (lang.code == normalized) return lang;
    }
    return KartaLanguage.english;
  }
}

